#!/usr/bin/env python3
"""Builds assets/map/omt_template.json from OpenFreeMap's Liberty style.

Liberty (github.com/hyperknot/openfreemap-styles, a fork of maputnik/osm-liberty, itself a fork of OSM Bright;
code BSD-3-Clause, design CC BY 4.0, repo MIT) is the starting point. This one-off script keeps its layer
structure (filters, widths, zoom stops, label layout) and replaces every colour with a palette role written
"@role". lib/maps/style/style_generator.dart fills the roles from a MapPalette. Run it only to re-base the
template on a newer Liberty; the template is what the app uses.

usage: make_omt_template.py liberty.json out.json
"""
import json
import re
import sys

src = json.load(open(sys.argv[1]))

# Needs the sprite sheet (icons and patterns), which the app does not ship, or is not wanted.
DROP = {
    'natural_earth', 'landcover_wetland', 'road_area_pattern', 'road_one_way_arrow', 'road_one_way_arrow_opposite',
    'poi_r20', 'poi_r7', 'poi_r1', 'poi_transit', 'highway-shield-non-us', 'highway-shield-us-interstate',
    'road_shield_us', 'building-3d',
}

FILL_ROLE = {
    'park': 'park', 'landcover_wood': 'wood', 'landcover_grass': 'grass', 'landcover_ice': 'ice',
    'landuse_pitch': 'pitch', 'landuse_track': 'pitch', 'landuse_cemetery': 'cemetery',
    'landuse_hospital': 'hospital', 'landuse_school': 'school', 'water': 'water', 'landcover_sand': 'sand',
    'aeroway_fill': 'aeroway', 'building': 'building', 'landuse_residential': 'residential',
}

def role_for_line(layer_id, colour):
    c = colour.replace(' ', '').lower() if isinstance(colour, str) else ''
    if layer_id.startswith('waterway'):
        return 'waterway'
    if layer_id.startswith('aeroway'):
        return 'aerowayLine'
    if layer_id == 'park_outline':
        return 'parkEdge'
    if layer_id.startswith('boundary'):
        return 'boundaryMinor' if layer_id == 'boundary_3' else 'boundary'
    if 'rail' in layer_id:
        return 'rail'
    if 'casing' in layer_id:
        if c in ('#e9ac77',):
            return 'roadMajorCasing'
        return 'roadMinorCasing'
    if 'path_pedestrian' in layer_id:
        return 'roadPath'
    if c in ('#fc8', 'hsl(26,87%,62%)') or layer_id.endswith('motorway') or layer_id.endswith('motorway_link'):
        return 'roadMotorway'
    if c in ('#fea', '#fff4c6'):
        return 'roadMajor'
    if c in ('#ffdaa6',):
        return 'roadMotorway'
    return 'roadMinor'

def text_roles(layer_id):
    if layer_id.startswith('waterway_line'):
        return 'labelWaterway', 'labelHalo'
    if layer_id.startswith('water_name'):
        return 'labelWater', 'labelHalo'
    if layer_id == 'highway-name-path':
        return 'labelPath', 'labelHalo'
    if layer_id.startswith('highway-name'):
        return 'labelRoad', 'labelHalo'
    if layer_id == 'airport':
        return 'labelRoad', 'labelHalo'
    if layer_id in ('label_other', 'label_state'):
        return 'labelMinor', 'labelHalo'
    return 'labelPlace', 'labelHalo'

def font(name):
    return name.replace('Noto Sans ', 'NotoSans-')

out = []
for l in src['layers']:
    if l['id'] in DROP:
        continue
    l = json.loads(json.dumps(l))
    paint = l.setdefault('paint', {})
    layout = l.get('layout', {})
    t = l['type']
    if t == 'background':
        paint['background-color'] = '@land'
    elif t == 'fill':
        role = FILL_ROLE[l['id']]
        paint['fill-color'] = '@' + role
        if 'fill-outline-color' in paint:
            paint['fill-outline-color'] = '@parkEdge' if l['id'] == 'park' else '@buildingEdge'
    elif t == 'line':
        paint['line-color'] = '@' + role_for_line(l['id'], paint.get('line-color'))
    elif t == 'symbol':
        tc, hc = text_roles(l['id'])
        paint['text-color'] = '@' + tc
        paint['text-halo-color'] = '@' + hc
        for k in [k for k in layout if k.startswith('icon-')]:
            del layout[k]
    # Fonts are folders named without spaces so the glyph address has nothing to escape.
    if isinstance(layout.get('text-font'), list):
        layout['text-font'] = [font(f) for f in layout['text-font']]
    out.append(l)

# Wetland becomes a plain tint (Liberty draws it with a sprite pattern).
for i, l in enumerate(out):
    if l['id'] == 'landcover_grass':
        wet = {'id': 'landcover_wetland', 'type': 'fill', 'source': 'openmaptiles', 'source-layer': 'landcover',
               'minzoom': 12, 'filter': ['==', ['get', 'class'], 'wetland'],
               'paint': {'fill-color': '@wetland'}}
        out.insert(i + 1, wet)
        break

json.dump({'note': 'Generated by tool/make_omt_template.py from OpenFreeMap Liberty. Colours are @roles.',
           'layers': out}, open(sys.argv[2], 'w'), indent=1)
roles = sorted(set(re.findall(r'"@(\w+)"', json.dumps(out))))
print(len(out), 'layers; roles:', ' '.join(roles))
