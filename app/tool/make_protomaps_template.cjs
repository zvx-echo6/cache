// Builds assets/map/protomaps_v4_template.json from the official @protomaps/basemaps package (BSD-3-Clause,
// https://github.com/protomaps/basemaps), the layer structure for Protomaps basemap tiles v4.
//
// The package itself generates the layers: this script hands it a "flavor" whose every colour is a
// placeholder "@<field>" (and "@pois.<field>", "@landcover.<field>"), then drops the layers that need the
// sprite sheet (icons) and removes icon properties from the labels that keep their text. The result keeps
// the package's filters, widths, zoom stops and label layout exactly; lib/maps/style/protomaps_layout.dart
// fills the placeholders from a MapPalette.
//
// usage: node make_protomaps_template.cjs <path to @protomaps/basemaps dist/cjs/index.cjs> <out.json>
// Tested with @protomaps/basemaps 5.7.2.
const fs = require('fs');
const pm = require(require('path').resolve(process.argv[2]));

const flavor = {};
for (const [k, v] of Object.entries(pm.LIGHT)) {
  if (typeof v === 'string') flavor[k] = '@' + k;
  else if (v && typeof v === 'object') {
    flavor[k] = {};
    for (const kk of Object.keys(v)) flavor[k][kk] = `@${k}.${kk}`;
  }
}
// Map fonts that ship with the app (assets/map/fonts).
flavor.regular = 'NotoSans-Regular';
flavor.bold = 'NotoSans-Bold';
flavor.italic = 'NotoSans-Italic';

const DROP = new Set(['roads_oneway', 'roads_shields', 'pois']);
const layers = [];
for (const l of pm.layers('protomaps', flavor, { lang: 'en' })) {
  if (DROP.has(l.id)) continue;
  const c = JSON.parse(JSON.stringify(l));
  if (c.layout) {
    for (const k of Object.keys(c.layout)) if (k.startsWith('icon-')) delete c.layout[k];
  }
  layers.push(c);
}
fs.writeFileSync(
  process.argv[3],
  JSON.stringify({ note: 'Generated by tool/make_protomaps_template.cjs from @protomaps/basemaps 5.7.2. Colours are @fields.', layers }, null, 1),
);
const fields = [...new Set(JSON.stringify(layers).match(/"@[\w.]+"/g))].map((s) => s.slice(2, -1)).sort();
console.log(layers.length + ' layers; fields: ' + fields.join(' '));
console.log('flavor fields: ' + Object.keys(flavor).join(' '));
